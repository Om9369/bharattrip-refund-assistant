import os, json, datetime as dt
import io
import pandas as pd
import streamlit as st
import recon, ai

st.set_page_config(page_title="BharatTrip Refund Reconciler", layout="wide")

# API key: from Streamlit secrets if present, else from the GEMINI_API_KEY environment variable
try:
    if "GEMINI_API_KEY" in st.secrets:
        os.environ["GEMINI_API_KEY"] = st.secrets["GEMINI_API_KEY"]
except Exception:
    pass

LOG_FILE = "informal_requests_log.csv"   # persists informal requests between restarts
LOG_COLS = ["new_id", "logged_at", "channel", "agent_name", "route", "issue_type",
            "urgency", "missing_info", "raw_message", "reply_draft", "status"]

def load_log():
    if os.path.exists(LOG_FILE):
        return pd.read_csv(LOG_FILE, dtype=str).fillna("")
    return pd.DataFrame(columns=LOG_COLS)

def next_id(log):
    return f"RF-NEW-{len(log) + 1:03d}"

TYPE_LABEL = {
    "GHOST_CLOSED": "Closed by Support, no Finance record",
    "STATUS_CONFLICT": "Support and Finance statuses disagree",
    "STUCK_PAYOUT": "Payout stuck in Finance",
    "UNEXPLAINED_DEDUCTION": "Short payment, no reason recorded",
    "AMOUNT_MISMATCH": "Paid amount does not match request",
    "FINANCE_ONLY": "In Finance but never logged by Support",
}

st.title("BharatTrip Refund Reconciler")
st.caption("Code matches the numbers; Gemini only handles messy text and drafts. A human approves every message.")

up = st.sidebar.file_uploader("Upload refund workbook (.xlsx)", type="xlsx")
asof = st.sidebar.date_input("Snapshot date", pd.Timestamp("2026-06-30"))
grace = 4   # longest Support -> Finance delay observed in the data
stuck = st.sidebar.slider("Days before payout is 'stuck'", 1, 15, 5)

t_morning, t_recon, t_intake = st.tabs(
    ["Morning report", "Reconcile & exceptions", "Informal request intake (AI)"])

# ---------- shared computation ----------
ex, m, log_lines = None, None, []
if up:
    S, F, E = recon.load(up)
    S, F = recon.clean(S, F, log_lines)
    m = recon.reconcile(S, F)
    ex = recon.exceptions(m, asof, grace, stuck, E)

# ---------- TAB 1: morning report ----------
with t_morning:
    st.subheader("What each team needs to act on today")
    informal = load_log()
    if ex is None:
        st.info("Upload the workbook in the sidebar to build the report.")
    else:
        def team_view(owner):
            v = ex[ex.owner == owner].copy()
            v["problem"] = v["type"].map(TYPE_LABEL)
            v["days waiting"] = v["age_days"]
            v["amount (INR)"] = v["amount"]
            return v[["id", "agent", "problem", "why", "days waiting", "amount (INR)"]]
        sup, fin = team_view("Support"), team_view("Finance")
        top = st.columns(4)
        top[0].metric("Support to act on", len(sup))
        top[1].metric("Finance to act on", len(fin))
        top[2].metric("Informal requests logged", len(informal))
        top[3].metric("INR waiting on actions", f"{ex.amount.sum():,.0f}")
        c1, c2 = st.columns(2)
        with c1:
            st.markdown("### Support to act on")
            if len(informal):
                st.markdown("**New informal requests (need a ticket confirmed)**")
                st.dataframe(informal[["new_id", "channel", "agent_name", "issue_type", "urgency"]],
                             hide_index=True, width="stretch")
            st.dataframe(sup, hide_index=True, width="stretch")
            st.download_button("Download Support list", sup.to_csv(index=False), "support_morning_list.csv")
        with c2:
            st.markdown("### Finance to act on")
            st.dataframe(fin, hide_index=True, width="stretch")
            st.download_button("Download Finance list", fin.to_csv(index=False), "finance_morning_list.csv")
        st.caption("Sorted by priority (days waiting x amount). In production this report would be "
                   "generated by a scheduled job each night and emailed to both teams.")

# ---------- TAB 2: reconcile & exceptions ----------
with t_recon:
    if ex is None:
        st.info("Upload the workbook in the sidebar.")
    else:
        with st.expander("Cleaning log"):
            for l in log_lines:
                st.write("• " + l)
        c = st.columns(4)
        c[0].metric("Matched in both", int((m.match_state == "both").sum()))
        c[1].metric("Support-only", int((m.match_state == "support_only").sum()))
        c[2].metric("Exceptions", len(ex))
        c[3].metric("INR at risk (ghost+stuck)",
                    f"{ex[ex.type.isin(['GHOST_CLOSED', 'STUCK_PAYOUT'])].amount.sum():,.0f}")
        st.dataframe(ex.groupby("type").agg(count=("id", "count"), rupees=("amount", "sum")).reset_index(),
                     hide_index=True)
        owner = st.radio("Owner", ["All", "Support", "Finance"], horizontal=True)
        v = ex if owner == "All" else ex[ex.owner == owner]
        if "escalated" in v.columns:
            if st.checkbox("Only exceptions that already became escalations"):
                v = v[v.escalated]
        st.dataframe(v, hide_index=True, width="stretch")
        pick = st.selectbox("Draft an agent reply for", v.id.tolist() if len(v) else [])
        if pick and st.button("Draft reply (Gemini)"):
            st.text_area("Draft - review before sending",
                         ai.draft_reply(v[v.id == pick].iloc[0].to_dict()), height=120)
        st.download_button("Download exceptions CSV", ex.to_csv(index=False), "exceptions.csv")
        st.markdown("### Unified ledger (proposed single source of truth)")
        st.caption("One row per refund. Support-owned and Finance-owned fields side by side, "
                   "plus a unified status and who must act next.")
        ledger = recon.build_ledger(m, ex, asof)
        st.dataframe(ledger, hide_index=True, width="stretch")
        buf = io.BytesIO()
        ledger.to_excel(buf, index=False)
        st.download_button("Download unified ledger (.xlsx)", buf.getvalue(), "refund_master_ledger.xlsx")

# ---------- TAB 3: informal intake ----------
with t_intake:
    st.subheader("Turn an email / WhatsApp message into a logged ticket")
    sample = "Bhai refund ka kya hua? BLR-MAA wala. 2 hafte ho gaye, koi jawab nahi."
    channel = st.selectbox("Channel", ["WhatsApp", "Email", "Phone"])
    msg = st.text_area("Paste the raw message", sample, height=120)
    if st.button("Parse & log"):
        log = load_log()
        new_id = next_id(log)
        try:
            parsed = ai.parse_intake(msg, ref=new_id)
        except Exception as e:
            parsed = {"issue_type": "other", "urgency": "medium", "missing_info": [],
                      "reply": f"Thanks, we have logged your request as {new_id}.",
                      "note": f"AI parsing failed ({e}); logged raw message"}
        row = {
            "new_id": new_id,
            "logged_at": dt.datetime.now().strftime("%Y-%m-%d %H:%M"),
            "channel": channel,
            "agent_name": parsed.get("agent_name") or "",
            "route": parsed.get("route") or "",
            "issue_type": parsed.get("issue_type", ""),
            "urgency": parsed.get("urgency", ""),
            "missing_info": ", ".join(parsed.get("missing_info", []) or []),
            "raw_message": msg,
            "reply_draft": parsed.get("reply", ""),
            "status": "Logged - awaiting Support confirmation",
        }
        log = pd.concat([log, pd.DataFrame([row])], ignore_index=True)
        log.to_csv(LOG_FILE, index=False)
        st.success(f"Logged as {new_id}")
        st.markdown("**Draft reply to the agent (human reviews before sending):**")
        st.info(row["reply_draft"])
        with st.expander("Raw AI output"):
            st.json(parsed)
    st.markdown("### Informal requests log")
    log = load_log()
    if len(log):
        st.dataframe(log, hide_index=True, width="stretch")
        st.download_button("Download log", log.to_csv(index=False), "informal_requests_log.csv")
        if st.button("Clear log (demo reset)"):
            os.remove(LOG_FILE)
            st.rerun()
    else:
        st.caption("No informal requests logged yet.")
